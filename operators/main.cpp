#include<iostream>
using namespace std;

int main() {
	//? Arithmetic Operators is used to perform basic mathematical operations on variables.
	int students = 101;

	students = students + 10;
	students+= 10;

	students = students - 10;
	students-= 10;

	students = students * 10;
	students*= 10;

	students = students / 10;
	students/= 10;

	students = students % 10;

	cout << students;

	return 0;
}