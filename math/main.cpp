#include<iostream>
#include<cmath>
using namespace std;

int main() {
	double x = 3;
	double y = 4;
	double z;

	z = max(x, y); //? max() is a function that returns the maximum of x and y
	z = min(x, y); //? min() is a function that returns the minimum of x and y
	z = pow(x, y); //? pow() is a function that returns the value of x raised to the power of y
	z = sqrt(x); //? sqrt() is a function that returns the square root of x
	z = abs(x); //? abs() is a function that returns the absolute value of x
	z = round(x); //? round() is a function that rounds x to the nearest integer
	z = ceil(x); //? ceil() is a function that rounds x up to the nearest integer
	z = floor(x); //? floor() is a function that rounds x down to the nearest integer


	return 0;
}